  function t(key, params) {
    const dict = M[currentLocale] || M.en;
    let str = dict[key] ?? M.en[key] ?? key;
    if (params) {
      Object.keys(params).forEach((k) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(params[k]));
      });
    }
    return str;
  }

  function getGreetings() {
    return GREETINGS[currentLocale] || GREETINGS.en;
  }

  function getMoodTitle(key) {
    const k = MOOD_TITLE_KEYS[key];
    return k ? t(k) : key;
  }

  function getMoodSnippet(key) {
    if (currentLocale === 'en') return null;
    return {
      title: t('mood.title.' + key),
      body: t('mood.body.' + key),
      closing: t('mood.closing.' + key)
    };
  }

  function getAnaQuestions() {
    return ANA_QUESTIONS[currentLocale] || ANA_QUESTIONS.en;
  }

  function getAnaUi() {
    return ANA_UI[currentLocale] || ANA_UI.en;
  }

  function getLocale() {
    return currentLocale;
  }

  function setLocale(loc, skipSave) {
    currentLocale = LOCALES.includes(loc) ? loc : 'en';
    document.documentElement.lang = LANG_ATTR[currentLocale] || 'en';
    if (!skipSave) {
      try { localStorage.setItem('ei_lang', currentLocale); } catch (_) {}
    }
    applyI18n();
    if (typeof onChange === 'function') onChange(currentLocale);
  }

  function initLocale(loc) {
    const fromStorage = (() => { try { return localStorage.getItem('ei_lang'); } catch (_) { return null; } })();
    const chosen = loc || fromStorage || 'en';
    setLocale(LOCALES.includes(chosen) ? chosen : 'en', true);
  }

  function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.placeholder = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.title = t(key);
    });
    document.querySelectorAll('option[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    const anaTitle = document.querySelector('.ana-title');
    if (anaTitle) anaTitle.textContent = getAnaUi().title;
    const anaLoad = document.querySelector('.ana-loading-text');
    if (anaLoad) anaLoad.textContent = getAnaUi().loading;
    const anaUi = getAnaUi();
    document.querySelectorAll('[data-i18n-ana]').forEach((el) => {
      const k = el.getAttribute('data-i18n-ana');
      if (k && anaUi[k]) el.textContent = anaUi[k];
    });
    updateThemeBtnsI18n();
  }

  function updateThemeBtnsI18n() {
    const isDark = document.documentElement.getAttribute('data-theme') !== 'light';
    const pdItem = document.getElementById('pdTheme');
    if (pdItem) pdItem.textContent = (isDark ? '  ' : '  ') + t(isDark ? 'pd.themeDark' : 'pd.themeLight');
  }

